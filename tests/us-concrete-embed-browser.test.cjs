'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');

test('demo navigation, geometry, decisions, report, file round trip and mobile layout', async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || undefined});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:930},acceptDownloads:true});
    const errors=[];
    page.on('pageerror', e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve(__dirname,'../developing.html')).href);
    await page.getByRole('article').filter({has:page.getByRole('heading',{name:'美标混凝土埋件计算'})})
      .getByRole('link').click();
    const status = page.locator('.judgement');
    assert.match(await status.innerText(),/满足/);
    assert.equal(await page.locator('#model-view svg').count(),1);
    const normal=await page.locator('.hero-metric strong').innerText();
    await page.locator('#preset').selectOption('edge');
    const near=await page.locator('.hero-metric strong').innerText();
    assert.notEqual(near,normal);
    await page.locator('[data-tab="loads"]').click();
    await page.locator('#p-vy').fill('850');
    assert.match(await status.innerText(),/超限/);
    await page.locator('#p-vy').fill('');
    assert.match(await status.innerText(),/待核/);
    await page.locator('#preset').selectOption('headed');
    await page.locator('#add-case').click();
    assert.equal(await page.locator('#load-cases tr').count(),4);
    await page.locator('#p-caseName').fill('浏览器复算');
    await page.locator('#p-vy').fill('27');
    const download = page.waitForEvent('download');
    await page.locator('#export-btn').click();
    const json=await fs.readFile(await (await download).path());
    await page.locator('#preset').selectOption('standard');
    await page.locator('#import-file').setInputFiles({name:'parameters.json',mimeType:'application/json',buffer:json});
    await page.getByRole('button',{name:'浏览器复算',exact:true}).waitFor();
    await page.reload();
    await page.getByRole('button',{name:'浏览器复算',exact:true}).waitFor();
    await page.locator('#report-btn').click();
    const report=page.locator('#embed-record');
    assert.match(await report.innerText(),/各荷载组合/);
    assert.match(await report.innerText(),/浏览器复算/);
    await report.getByText('公式与条款',{exact:true}).first().click();
    assert.match(await report.innerText(),/AVc \/ AVco/);
    await page.emulateMedia({media:'print'});
    const pdf=await page.pdf({format:'A4'});
    assert.ok(pdf.length>12000);
    await page.emulateMedia({media:'screen'});
    await report.getByRole('button',{name:'返回模型'}).click();
    await page.locator('#paper-btn').click();
    assert.match(await page.locator('#embed-record').innerText(),/0\.943/);
    await page.keyboard.press('Escape');
    await page.locator('[data-supp="rebar"]').click();
    await page.getByRole('button',{name:'填入独立算例'}).click();
    assert.match(await page.locator('dialog[open]').innerText(),/190.8/);
    await page.keyboard.press('Escape');
    await page.reload();
    await page.locator('#report-btn').click();
    assert.match(await report.innerText(),/带肋钢筋标准钩 · 独立工况/);
    assert.match(await report.innerText(),/独立演示算例/);
    await page.keyboard.press('Escape');
    await page.locator('#preset').selectOption('standard');
    await page.locator('#report-btn').click();
    assert.doesNotMatch(await report.innerText(),/带肋钢筋标准钩 · 独立工况/);
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    assert.deepEqual(errors,[]);
  } finally { await browser.close(); }
});
